//! The Markdown of the generated block.

use super::{END_MARKER, Publication, START_MARKER, group, publication_of};
use crate::clock::format_utc;
use crate::file_store::history_language::HistoryLanguage;
use crate::file_store::model::TaskView;

fn one_line(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

fn state_of(task: &TaskView, language: HistoryLanguage) -> String {
    let mut parts = vec![task.task_status.as_str().to_owned()];
    if task.archived_at.is_some() {
        parts.push(language.text("archived", "アーカイブ済み").to_owned());
    }
    parts.join(", ")
}

fn item_line(task: &TaskView, language: HistoryLanguage, detail: bool) -> String {
    let done = task.acceptance.iter().filter(|a| a.done).count();
    let mut line = format!(
        "- #{} {} ({}; {} {}/{})",
        task.id,
        one_line(&task.title),
        state_of(task, language),
        language.text("acceptance", "受入条件"),
        done,
        task.acceptance.len()
    );
    if detail {
        line.push_str(&format!(
            "\n  - {}: `agboard show {}`, {} {}, {} {}",
            language.text("Source", "原記録"),
            task.id,
            language.text("results", "成果"),
            task.results.len(),
            language.text("history entries", "履歴"),
            task.history.len()
        ));
        for result in &task.results {
            let link = result
                .link
                .as_deref()
                .map(|l| format!(" ({l})"))
                .unwrap_or_default();
            line.push_str(&format!(
                "\n  - {}: {} [{}, {}]{}",
                language.text("Result", "成果"),
                one_line(&result.title),
                result.kind.as_str(),
                format_utc(result.at),
                link
            ));
        }
    }
    line
}

/// The generated block for `version`, from the marker line to the marker line, ending with a
/// newline. Nothing in it depends on the time of generation, so generating twice from the
/// same board gives the same text.
pub fn render_block(tasks: &[TaskView], version: &str, language: HistoryLanguage) -> String {
    let groups = group(tasks, version);
    let t = |en: &'static str, ja: &'static str| language.text(en, ja);
    let mut out = String::new();
    out.push_str(START_MARKER);
    out.push('\n');
    out.push_str(&format!(
        "{}\n\n",
        t(
            "<!-- Generated by `agboard release doc`. Edit outside this block: regenerating replaces only what is between the markers. -->",
            "<!-- `agboard release doc` が生成しました。編集はこのブロックの外で行ってください。再生成で置き換わるのはマーカーの間だけです。 -->"
        )
    ));
    out.push_str(&format!(
        "## {} {version}\n\n",
        t("Release status of", "リリースの状況:")
    ));
    out.push_str(&format!(
        "- {}: {}\n- {}: {}\n- {}: {}\n- {}: {}\n\n",
        t("Planned", "予定"),
        groups.planned.len(),
        t("Verified", "検証済み"),
        groups.verified.len(),
        t("Remaining", "残作業"),
        groups.remaining.len(),
        t("Moved to the next version", "次版送り"),
        groups.moved.len()
    ));
    out.truncate(out.len() - 1);
    out.push_str(&format!(
        "- {}: {} / {}\n\n",
        t(
            "Published (with a publication record)",
            "公開済み(公開記録あり)"
        ),
        groups.published.len(),
        groups.planned.len()
    ));
    let section = |out: &mut String, title: &str, lines: Vec<String>, empty: &str| {
        out.push_str(&format!("### {title}\n\n"));
        if lines.is_empty() {
            out.push_str(&format!("{empty}\n\n"));
        } else {
            for line in lines {
                out.push_str(&line);
                out.push('\n');
            }
            out.push('\n');
        }
    };
    section(
        &mut out,
        t("Planned", "予定"),
        groups
            .planned
            .iter()
            .map(|task| item_line(task, language, false))
            .collect(),
        t(
            "No task is planned for this version.",
            "この版に予定したタスクはありません。",
        ),
    );
    section(
        &mut out,
        t("Verified", "検証済み"),
        groups
            .verified
            .iter()
            .map(|task| item_line(task, language, true))
            .collect(),
        t(
            "No task has all its acceptance conditions done.",
            "受入条件をすべて満たしたタスクはまだありません。",
        ),
    );
    section(
        &mut out,
        t("Remaining", "残作業"),
        groups
            .remaining
            .iter()
            .map(|task| item_line(task, language, true))
            .collect(),
        t("Nothing remains.", "残作業はありません。"),
    );
    section(
        &mut out,
        t("Moved to the next version", "次版送り"),
        groups
            .moved
            .iter()
            .map(|item| {
                let to = match item.moved_to.as_ref().and_then(|v| v.as_deref()) {
                    Some(v) => v.to_owned(),
                    None => t("no planned version", "予定なし").to_owned(),
                };
                let at = item.moved_at.map(format_utc).unwrap_or_default();
                format!(
                    "{}\n  - {}: {} ({})",
                    item_line(item.task, language, true),
                    t("Moved to", "移動先"),
                    to,
                    at
                )
            })
            .collect(),
        t(
            "No task was moved out of this version.",
            "この版から外れたタスクはありません。",
        ),
    );
    out.push_str(&format!("### {}\n\n", t("Publication", "公開")));
    out.push_str(&format!(
        "{}\n\n",
        t(
            "A task counts as published only when one of its results states `Published: VERSION` on its own line and links to what was published. Done alone is not publication. Generating this document publishes nothing.",
            "タスクを公開済みと数えるのは、成果の本文に `Published: 版名` の行があり、公開物へのリンクが付いている場合だけです。Done だけでは公開済みになりません。この文書を生成しても何も公開されません。",
        )
    ));
    let mut confirmed = Vec::new();
    let mut unconfirmed = Vec::new();
    for task in &groups.planned {
        let head = item_line(task, language, false);
        match publication_of(task, version) {
            Publication::Confirmed(result) => confirmed.push(format!(
                "{head}\n  - {}: `agboard show {}`, {} {} [{}] ({})",
                t("Record", "公開記録"),
                task.id,
                t("result", "成果"),
                result.version,
                format_utc(result.at),
                result.link.as_deref().unwrap_or_default()
            )),
            Publication::Unlinked(result) => unconfirmed.push(format!(
                "{head}\n  - {}: {} {} {}",
                t("Unconfirmed", "未確認"),
                t("result", "成果"),
                result.version,
                t(
                    "states the publication but has no link",
                    "は公開と書いているがリンクがない"
                )
            )),
            Publication::None => unconfirmed.push(format!(
                "{head}\n  - {}: {}",
                t("Unconfirmed", "未確認"),
                t("no publication record", "公開記録がない")
            )),
        }
    }
    section(
        &mut out,
        t("Published", "公開済み"),
        confirmed,
        t(
            "No task has a publication record.",
            "公開記録のあるタスクはありません。",
        ),
    );
    section(
        &mut out,
        t("Not confirmed as published", "公開を確認できない"),
        unconfirmed,
        t(
            "Every planned task has a publication record.",
            "予定したタスクはすべて公開記録を確認できました。",
        ),
    );
    out.push_str(END_MARKER);
    out.push('\n');
    out
}
